/**
 * PIXN Sync Pro - Background Service Worker (Manifest V3)
 * Bridges Pix'n Retro Discord session authentication and communicates with PIXN Manager Pro.
 */

const DEFAULT_SERVER = 'http://127.0.0.1:8989';

// Retrieve session cookie from pixn-retro.dedyn.io with comprehensive matching
async function getPixnSessionCookie() {
    try {
        // 1. Try URL matching releases endpoint
        let cookie = await chrome.cookies.get({
            url: 'https://pixn-retro.dedyn.io/releases',
            name: 'session'
        });
        if (cookie && cookie.value) {
            return cookie.value.startsWith('session=') ? cookie.value : ('session=' + cookie.value);
        }

        // 2. Try URL matching origin root
        cookie = await chrome.cookies.get({
            url: 'https://pixn-retro.dedyn.io/',
            name: 'session'
        });
        if (cookie && cookie.value) {
            return cookie.value.startsWith('session=') ? cookie.value : ('session=' + cookie.value);
        }

        // 3. Search all cookies for pixn-retro.dedyn.io domain
        const domainCookies = await chrome.cookies.getAll({ domain: 'pixn-retro.dedyn.io' });
        if (domainCookies && domainCookies.length > 0) {
            const sess = domainCookies.find(c => c.name === 'session');
            if (sess && sess.value) {
                return sess.value.startsWith('session=') ? sess.value : ('session=' + sess.value);
            }
            const fallback = domainCookies.find(c => /session|token|auth|discord/i.test(c.name));
            if (fallback && fallback.value) {
                return fallback.value.startsWith('session=') ? fallback.value : `${fallback.name}=${fallback.value}`;
            }
        }

        // 4. Search all cookies accessible to the releases URL
        const urlCookies = await chrome.cookies.getAll({ url: 'https://pixn-retro.dedyn.io/releases' });
        if (urlCookies && urlCookies.length > 0) {
            const sess = urlCookies.find(c => c.name === 'session');
            if (sess && sess.value) {
                return sess.value.startsWith('session=') ? sess.value : ('session=' + sess.value);
            }
            const fallback = urlCookies.find(c => /session|token|auth|discord/i.test(c.name));
            if (fallback && fallback.value) {
                return fallback.value.startsWith('session=') ? fallback.value : `${fallback.name}=${fallback.value}`;
            }
        }
    } catch (e) {
        console.warn('Error reading cookie via chrome.cookies:', e);
    }
    return null;
}

// Retrieve bundled server_config.json from extension folder (auto-generated by PIXN)
async function getBundledServerConfig() {
    try {
        const url = chrome.runtime.getURL('server_config.json');
        const res = await fetch(url);
        if (res.ok) {
            const data = await res.json();
            if (data && data.target_server) {
                return data.target_server.trim().replace(/\/+$/, '');
            }
        }
    } catch (e) {}
    return null;
}

// Get configured target server from extension storage or bundled server_config.json
async function getTargetServer() {
    return new Promise(async (resolve) => {
        chrome.storage.local.get(['pixn_target_server', 'pixn_target_server_manual'], async (result) => {
            const bundled = await getBundledServerConfig();

            // 1. If user explicitly manually set and saved a custom server in popup, respect it
            if (result && result.pixn_target_server && result.pixn_target_server_manual) {
                return resolve(result.pixn_target_server.replace(/\/+$/, ''));
            }

            // 2. If bundled server_config.json is present, adopt it
            if (bundled) {
                if (!result.pixn_target_server || result.pixn_target_server === DEFAULT_SERVER || !result.pixn_target_server_manual) {
                    await chrome.storage.local.set({ pixn_target_server: bundled, pixn_target_server_manual: false });
                }
                return resolve(bundled);
            }

            // 3. Fallback to storage or default
            let srv = (result && result.pixn_target_server) || DEFAULT_SERVER;
            resolve(srv.replace(/\/+$/, ''));
        });
    });
}

// Set configured target server
async function setTargetServer(serverUrl, isManual = true) {
    const clean = (serverUrl || DEFAULT_SERVER).trim().replace(/\/+$/, '');
    await chrome.storage.local.set({ pixn_target_server: clean, pixn_target_server_manual: isManual });
    return clean;
}

// Direct background forwarder to save session cookie into PIXN config
async function saveCookieToServer(serverUrl, cookieValue) {
    if (!serverUrl || !cookieValue) return { success: false, error: 'Missing server or cookie' };
    const srv = serverUrl.replace(/\/+$/, '');
    const cleanCookie = cookieValue.startsWith('session=') ? cookieValue : ('session=' + cookieValue);

    // 1. Try save_config endpoint
    try {
        const res = await fetch(`${srv}/save.php?action=save_config`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ pixn_session_cookie: cleanCookie })
        });
        const data = await res.json();
        if (data && (data.status === 'ok' || data.status === 'success')) {
            return { success: true, method: 'save_config', response: data };
        }
    } catch (e) {
        console.warn('save_config attempt failed:', e);
    }

    // 2. Fallback to save_systems endpoint
    try {
        const res = await fetch(`${srv}/save.php?action=save_systems`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ systems: [], cookie: cleanCookie })
        });
        const data = await res.json();
        return { success: true, method: 'save_systems', response: data };
    } catch (err) {
        console.warn('save_systems attempt failed:', err);
        return { success: false, error: err.message };
    }
}

// Message handler
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
    if (message.action === 'get_session_cookie') {
        getPixnSessionCookie().then(cookie => {
            sendResponse({ success: Boolean(cookie), cookie: cookie });
        });
        return true; // Keep message channel open for async response
    }

    if (message.action === 'save_session_cookie') {
        getTargetServer().then(targetServer => {
            const srv = message.server || targetServer || DEFAULT_SERVER;
            saveCookieToServer(srv, message.cookie).then(result => {
                sendResponse(result);
            });
        });
        return true;
    }

    if (message.action === 'get_target_server') {
        getTargetServer().then(async server => {
            const bundled = await getBundledServerConfig();
            sendResponse({ server: server, bundled_server: bundled });
        });
        return true;
    }

    if (message.action === 'set_target_server') {
        setTargetServer(message.server, message.isManual !== false).then(saved => {
            sendResponse({ success: true, server: saved });
        });
        return true;
    }

    if (message.action === 'check_server_health') {
        const srv = (message.server || DEFAULT_SERVER).replace(/\/+$/, '');
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 3500);

        fetch(`${srv}/save.php?action=get_config&t=${Date.now()}`, {
            method: 'GET',
            signal: controller.signal
        })
        .then(res => res.json())
        .then(data => {
            clearTimeout(timeoutId);
            sendResponse({ online: true, data: data });
        })
        .catch(err => {
            clearTimeout(timeoutId);
            sendResponse({ online: false, error: err.message });
        });
        return true;
    }

    if (message.action === 'forward_sync_data') {
        const srv = (message.server || DEFAULT_SERVER).replace(/\/+$/, '');
        fetch(`${srv}/save.php?action=save_systems`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(message.payload)
        })
        .then(res => res.json())
        .then(resData => {
            sendResponse({ success: true, response: resData });
        })
        .catch(err => {
            sendResponse({ success: false, error: err.message });
        });
        return true;
    }
});
